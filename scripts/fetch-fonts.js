// One-off: download the app's two Google Fonts (OFL) into www/fonts so the app never needs
// the internet to look right. Kept so the fonts can be refreshed later:  node scripts/fetch-fonts.js
const fs = require('node:fs');
const path = require('node:path');

const CSS_URL = 'https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,400;12..96,500;12..96,600;12..96,700&family=Rozha+One&display=swap';
// A desktop Chrome user agent makes Google serve woff2.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
const KEEP = new Set(['latin', 'latin-ext']); // latin-ext carries the rupee sign (U+20B9)
const LICENSES = {
  'OFL-BricolageGrotesque.txt': 'https://raw.githubusercontent.com/google/fonts/main/ofl/bricolagegrotesque/OFL.txt',
  'OFL-RozhaOne.txt': 'https://raw.githubusercontent.com/google/fonts/main/ofl/rozhaone/OFL.txt',
};
const OUT = path.join(__dirname, '..', 'www', 'fonts');

async function get(url, binary) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${res.status} for ${url}`);
  return binary ? Buffer.from(await res.arrayBuffer()) : res.text();
}

async function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const css = await get(CSS_URL);
  // Each block looks like: /* latin */ @font-face { font-family: 'X'; ... src: url(...) format('woff2'); unicode-range: ...; }
  const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)];
  const files = new Map(); // remote url -> local name
  const kept = [];
  for (const [, subset, block] of blocks) {
    if (!KEEP.has(subset)) continue;
    const family = /font-family:\s*'([^']+)'/.exec(block)[1];
    const url = /url\(([^)]+)\)/.exec(block)[1];
    if (!files.has(url)) {
      const slug = family.toLowerCase().replace(/\s+/g, '-');
      files.set(url, `${slug}-${subset}.woff2`);
    }
    kept.push(`/* ${family}, ${subset} */\n` + block.replace(url, files.get(url)));
  }
  if (!kept.length) throw new Error('no latin font blocks found; did Google change its CSS?');
  for (const [url, name] of files) fs.writeFileSync(path.join(OUT, name), await get(url, true));
  fs.writeFileSync(path.join(OUT, 'fonts.css'),
    '/* Self-hosted Google Fonts (SIL Open Font License, see OFL-*.txt). Generated by scripts/fetch-fonts.js */\n' + kept.join('\n') + '\n');
  for (const [name, url] of Object.entries(LICENSES)) fs.writeFileSync(path.join(OUT, name), await get(url));
  console.log(`fonts.css with ${kept.length} @font-face blocks, ${files.size} woff2 files, ${Object.keys(LICENSES).length} licences`);
}

main().catch(e => { console.error(e.message); process.exit(1); });
